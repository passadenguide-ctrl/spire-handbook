existing_ids = {e["id"] for e in extra_list}
for extra_id, (fname, name_ru, name_en, req, ref) in docx_files.items():
    if extra_id not in existing_ids:
        fpath = os.path.join(docx_dir, fname)
        desc = ""
        quote = ""
        abilities = []
        if os.path.exists(fpath):
            with zipfile.ZipFile(fpath) as z:
                tree = ET.fromstring(z.read("word/document.xml"))
                paragraphs = [''.join(node.text for node in p.iter('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}t') if node.text).strip() for p in tree.iter('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}p')]
                full_txt = "\n".join([p for p in paragraphs if p])
                
                # Extract quote
                q_match = re.search(r'[«"]([^»"]+)[»"]', full_txt)
                if q_match:
                    quote = q_match.group(1).strip()
                
                # Extract description
                d_match = re.search(r'[»"]\s*([\s\S]*?)(?=ПРОДВИЖЕНИЯ|СПОСОБНОСТИ|УРОВНЯ|$)', full_txt, re.IGNORECASE)
                if d_match:
                    desc = " ".join([l.strip() for l in d_match.group(1).splitlines() if l.strip()])[:600]

        extra_list.append({
            "id": extra_id,
            "nameRu": name_ru,
            "nameEn": name_en,
            "quote": quote,
            "description": desc,
            "requirement": req,
            "refresh": ref,
            "image": f"assets/images/extra/{extra_id}.png",
            "abilities": [
                {
                    "id": f"{extra_id}-core",
                    "name": f"Дар {name_ru}",
                    "tier": "low",
                    "tag": "Оккультный",
                    "description": f"Первая ступень посвящения в путь {name_ru}. Открывает связь с силами организации."
                }
            ]
        })

